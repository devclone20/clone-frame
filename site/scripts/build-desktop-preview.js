#!/usr/bin/env node
/* Builds a fully self-contained "CLONE FRAME.html" on the Desktop.
 *
 * WHY: the production index.html loads the .glb robots + pass-card PNG over
 * http (correct for Hostinger). But when you DOUBLE-CLICK index.html, the
 * browser uses the file:// protocol and blocks those local asset fetches for
 * security — so the robots silently fail to load and the page looks "broken".
 *
 * This script inlines every local asset as a data: URI, producing one
 * standalone file that works on double-click with NO server. three.js still
 * comes from the CDN (works over file://, just needs internet).
 *
 * Run after ANY change to index.html or the assets:
 *     node scripts/build-desktop-preview.js
 */
const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..');                 // clone-frame-site/
const OUT  = path.join(SITE, 'CLONE FRAME.html');           // co-located double-click preview

let html = fs.readFileSync(path.join(SITE, 'cloneframe.html'), 'utf8');

const dataURI = (rel, mime) =>
  `data:${mime};base64,${fs.readFileSync(path.join(SITE, rel)).toString('base64')}`;

// Every local asset the page references (verified with grep). Add to this list
// if index.html starts referencing new local files.
const subs = [
  ['assets/models/iclone-idle.glb',   dataURI('assets/models/iclone-idle.glb', 'model/gltf-binary')],
  ['assets/models/iclone-run.glb',    dataURI('assets/models/iclone-run.glb',  'model/gltf-binary')],
  ['assets/models/iclone-flip.glb',   dataURI('assets/models/iclone-flip.glb', 'model/gltf-binary')],
  ['assets/img/og-pass-card.png?v=2', dataURI('assets/img/og-pass-card.png',   'image/png')],
];

const report = [];
for (const [needle, replacement] of subs) {
  const count = html.split(needle).length - 1;
  if (count === 0) { console.error('!! reference not found in index.html:', needle); process.exit(1); }
  html = html.split(needle).join(replacement);
  report.push(`  ${needle}  ->  data: URI  (x${count})`);
}

html = html.replace('<head>',
  '<head>\n<!-- CLONE FRAME - OFFLINE PREVIEW BUILD. Assets embedded as data: URIs.\n' +
  '     Double-click to view (no server needed). Generated by\n' +
  '     clone-frame-site/scripts/build-desktop-preview.js from index.html.\n' +
  '     The PRODUCTION file is clone-frame-site/index.html (loads assets over http). -->');

fs.writeFileSync(OUT, html);

const leftovers = (html.match(/(src|href)="assets\//g) || []).length
                + (html.match(/url\(assets\//g) || []).length;
console.log('Embedded:\n' + report.join('\n'));
console.log(`\nWrote: ${OUT}  (${(fs.statSync(OUT).size / 1e6).toFixed(2)} MB)`);
console.log(`Remaining local asset refs (must be 0): ${leftovers}`);
if (leftovers !== 0) process.exit(1);
